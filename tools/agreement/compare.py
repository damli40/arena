def strict_same(a, b):
    """Equal and the same JSON type: 0 is not -0.0, 1 is not true, 5 is not 5.0."""
    if type(a) is not type(b):
        return False
    if isinstance(a, float):
        return a == b and math.copysign(1, a) == math.copysign(1, b)
    if isinstance(a, dict):
        return a.keys() == b.keys() and all(strict_same(a[k], b[k]) for k in a)
    if isinstance(a, list):
        return len(a) == len(b) and all(strict_same(x, y) for x, y in zip(a, b))
    return a == b


def gate_call(c):
    return {"actor": c["actor"], "target": c.get("target", "vault"), "method": c["method"],
            "args": c.get("args", {}), "gas_tgas": c.get("gas_tgas"), "deposit_yocto": c.get("deposit_yocto")}


def gate_plan(steps):
    """What the gatekeeper believes each step is, in the engine's plan shape."""
    out = []
    for st in steps:
        (k, v), = st.items()
        if k == "call":
            out.append({"kind": "call", "call": gate_call(v)})
        elif k == "race":
            out.append({"kind": "race", "calls": [gate_call(e["call"] if isinstance(e, dict) and set(e) == {"call"} else e) for e in v]})
        elif k == "view":
            out.append({"kind": "view", "target": v.get("target", "vault"), "method": v["method"], "args": v.get("args", {})})
        elif k in ("wait_blocks", "wait_seconds"):
            out.append({"kind": k, "n": v})
        else:
            out.append({"kind": "add_key", "actor": v["actor"], "permission": v.get("permission", "full_access")})
    return out


def first_difference(a, b, path="steps"):
    if isinstance(a, dict) and isinstance(b, dict):
        for k in sorted(set(a) | set(b)):
            if k not in a or k not in b or not strict_same(a[k], b[k]):
                return first_difference(a.get(k), b.get(k), f"{path}.{k}")
    if isinstance(a, list) and isinstance(b, list) and len(a) == len(b):
        for i, (x, y) in enumerate(zip(a, b)):
            if not strict_same(x, y):
                return first_difference(x, y, f"{path}[{i}]")
    return f"{path}: gatekeeper read {json.dumps(a)[:80]}, engine would use {json.dumps(b)[:80]}"


def gatekeeper(path, suite):
    try:
        err = V.validate_path(path, intents_suite=suite == "intents", chainsig_suite=suite == "chainsig")
    except BaseException as e:  # noqa: BLE001 - a crash is itself a finding
        return "crash", f"{type(e).__name__}: {str(e)[:120]}"
    return ("reject", err.split(": ", 1)[-1]) if err else ("accept", None)


SUITE_FLAGS = {"main": [], "intents": ["--intents"], "chainsig": ["--chainsig"]}


def run_engine(harness, folder, suite):
    cmd = harness + ["check-seq"] + SUITE_FLAGS[suite] + [str(folder)]
    p = subprocess.run(cmd, capture_output=True, text=True)
    if p.returncode != 0:
        sys.exit(f"engine check-seq failed (exit {p.returncode}): {p.stderr[-2000:]}")
    out = {}
    for line in p.stdout.split("\n"):  # not splitlines(): it also splits on U+2028 and U+0085 inside an arg
        if line.startswith("{"):
            j = json.loads(line)
            out[pathlib.Path(j["file"]).name] = j
    return out


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=20261112)
    ap.add_argument("--random", type=int, default=3000, help="random files to add to the hand cases")
    ap.add_argument("--harness", help="path to a built arena-harness (default: cargo run --release --offline)")
    ap.add_argument("--keep", help="write the files here and keep them")
    ap.add_argument("--verbose", action="store_true")
    a = ap.parse_args(argv)
    harness = [a.harness] if a.harness else ["cargo", "run", "--release", "--offline", "--quiet",
                                             "--manifest-path", str(ROOT / "harness" / "Cargo.toml"), "--"]
    cases = hand_cases() + random_cases(a.seed, a.random)
    work = pathlib.Path(a.keep) if a.keep else pathlib.Path(tempfile.mkdtemp(prefix="arena-agree-"))
    dirs = {s: work / s for s in SUITE_FLAGS}
    for d in dirs.values():
        shutil.rmtree(d, ignore_errors=True)
        d.mkdir(parents=True)
    names = {}
    for n, (label, text, suite) in enumerate(cases):
        fn = f"{n:05d}-" + re.sub(r"[^A-Za-z0-9._^-]", "_", label)[:60] + ".json"
        (dirs[suite] / fn).write_bytes(text.encode("utf-8", "surrogatepass"))
        names[(suite, fn)] = label
    engine = {}
    for suite, d in dirs.items():
        for fn, j in run_engine(harness, d, suite).items():
            engine[(suite, fn)] = j

    fails, engine_only, both_ok, both_no = [], [], 0, 0
    for (suite, fn), label in sorted(names.items(), key=lambda x: x[1]):
        path = dirs[suite] / fn
        g, why = gatekeeper(path, suite)
        e = engine.get((suite, fn))
        if e is None:
            fails.append((label, "engine printed no line for this file"))
            continue
        if g == "crash":
            fails.append((label, f"gatekeeper crashed instead of giving a reason: {why}"))
        elif g == "accept" and not e["ok"]:
            fails.append((label, f"gatekeeper accepts, engine refuses: {e['error'][:160]}"))
        elif g == "accept":
            gp = gate_plan(json.loads(path.read_text(encoding="utf-8")).get("steps"))
            if not strict_same(gp, e["steps"]):
                fails.append((label, "engine would run it differently: " + first_difference(gp, e["steps"])))
            else:
                both_ok += 1
        elif e["ok"]:
            engine_only.append((label, why))
        else:
            both_no += 1
    if a.verbose:
        for label, why in engine_only:
            print(f"  engine-only accepts {label}: gatekeeper says {why}")
    for label, why in fails:
        print(f"DISAGREE {label}: {why}")
    if not a.keep:
        shutil.rmtree(work, ignore_errors=True)
    print(f"agreement: {len(cases)} files (seed {a.seed}), {len(fails)} disagreements; "
          f"both accept {both_ok} and read them the same, both refuse {both_no}, "
          f"engine-only accepts {len(engine_only)} (the gatekeeper is meant to be stricter)")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
