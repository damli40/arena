# ---------------------------------------------------------------- building files

def meta_for(steps, **over):
    m = {"id": "agree-case", "title": "comparison test case", "source": "hand", "kind": "sequence",
         "breaks": "nothing; generated by tools/agreement/compare.py",
         "expected_safe_result": "n/a", "added": "2026-11-12", "author": "tools/agreement/compare.py",
         "steps_sha256": SHA_PLACEHOLDER}
    m.update(over)
    return m


def doc_text(doc, raw=None):
    """JSON text for a doc. `raw` maps a sentinel string to raw JSON text spliced in, for things
    json.dumps cannot write (lone surrogates, NaN, -0, duplicate keys, huge numbers). Then the
    steps hash is filled in from what Python reads back, so meta never hides a steps problem."""
    t = json.dumps(doc, indent=1)
    for k, v in (raw or {}).items():
        assert json.dumps(k) in t, k
        t = t.replace(json.dumps(k), v)
    if SHA_PLACEHOLDER in t:
        try:
            back = json.loads(t)
            t = t.replace(SHA_PLACEHOLDER, V.steps_hash(back["steps"]))
        except Exception:
            pass  # unreadable or odd steps: leave the placeholder, the gatekeeper will say why
    return t


def attack(steps, name="agree-case", **meta_over):
    return {"name": name, "steps": steps, "meta": meta_for(steps, **meta_over)}


def call(actor="agent", method="pay", **kw):
    c = {"actor": actor, "method": method}
    c.update(kw)
    return {"call": c}


