def random_value(r):
    return r.choice([None, True, False, 0, 1, -1, 7, 200, 201, 300, 301, 2**63 - 1, 2**63, 2**64, 10**18, 10**18 + 1,
                     1.5, 0.0, "", "pay", "agent", "outsider", "owner", "vault", "token", "intents", "x" * 129,
                     [], [1], {}, {"actor": "agent", "method": "pay"}, {"call": {"actor": "agent", "method": "pay"}}])


def random_valid_call(r, targets):
    c = {"actor": r.choice(V.ACTORS), "method": r.choice(["pay", "cancel", "ft_transfer", "set_cap", "m_" + str(r.randint(0, 99))])}
    if r.random() < 0.6:
        c["target"] = r.choice(targets)
    if r.random() < 0.8:
        c["args"] = {r.choice(["id", "amount", "receiver_id", "account_id", "memo"]): r.choice(["inv-1", "sam", "agent", "100", 5, True, None, [1, "a"], {"x": 1}])
                     for _ in range(r.randint(0, 3))}
    if r.random() < 0.3:
        c["gas_tgas"] = r.randint(V.GAS_MIN, V.GAS_MAX)
    if r.random() < 0.3:
        c["deposit_yocto"] = r.choice([0, 1, 10**18, r.randint(0, 10**18)])
    return c


def random_valid_steps(r, targets):
    n = r.randint(1, V.MAX_STEPS)
    steps, wait_s = [], 0
    for _ in range(n):
        k = r.choice(["call", "call", "view", "race", "wait_blocks", "wait_seconds", "add_key"])
        if k == "call":
            steps.append({"call": random_valid_call(r, targets)})
        elif k == "view":
            v = {"method": r.choice(["get_invoice", "ft_balance_of", "get_config"])}
            if r.random() < 0.5:
                v["target"] = r.choice(targets)
            if r.random() < 0.5:
                v["args"] = {"id": "inv-1"}
            steps.append({"view": v})
        elif k == "race":
            els = [random_valid_call(r, targets) for _ in range(r.randint(V.RACE_MIN, V.RACE_MAX))]
            steps.append({"race": [({"call": e} if r.random() < 0.3 else e) for e in els]})
        elif k == "wait_blocks":
            steps.append({"wait_blocks": r.randint(1, V.MAX_WAIT_BLOCKS)})
        elif k == "wait_seconds":
            s = r.randint(1, min(V.MAX_WAIT_SECONDS, max(1, V.MAX_TOTAL_WAIT_SECONDS - wait_s)))
            if wait_s + s <= V.MAX_TOTAL_WAIT_SECONDS:
                wait_s += s
                steps.append({"wait_seconds": s})
        else:
            a = {"actor": r.choice(V.ACTORS)}
            if r.random() < 0.5:
                a["permission"] = r.choice(V.ADD_KEY_PERMISSIONS)
            steps.append({"add_key": a})
    if not any(set(s) & {"call", "race", "add_key"} for s in steps):
        steps.append({"call": random_valid_call(r, targets)})
    return steps[:V.MAX_STEPS]


def mutate(r, steps):
    """One random change somewhere in the steps: replace a value, drop or add a key, wrap,
    nest, duplicate."""
    steps = json.loads(json.dumps(steps))
    i = r.randrange(len(steps))
    st = steps[i]
    if not (isinstance(st, dict) and st):  # an earlier mutation broke this step: replace it
        steps[i] = st = {"call": {"actor": "agent", "method": "pay"}}
    k, v = next(iter(st.items()))
    m = r.randint(0, 9)
    if m == 0:
        steps[i] = {r.choice(["exec", "calls", "Race", "wait", "view_call"]): v}
    elif m == 1:
        st[r.choice(V.STEP_KEYS)] = random_value(r)  # may add a second key
    elif m == 2:
        steps[i] = {k: random_value(r)}
    elif m == 3 and isinstance(v, dict) and v:
        v[r.choice(list(v))] = random_value(r)
    elif m == 4 and isinstance(v, dict) and v:
        del v[r.choice(list(v))]
    elif m == 5 and isinstance(v, dict):
        v[r.choice(["code", "script", "call", "target", "gas", "actor", "permission"])] = random_value(r)
    elif m == 6 and isinstance(v, list) and v:
        j = r.randrange(len(v))
        v[j] = r.choice([random_value(r), {"view": {"method": "get"}}, {"race": [v[0], v[0]]}, {"call": v[j], "x": 1}])
    elif m == 7:
        steps.insert(i, st)  # may push past 12 steps
    elif m == 8:
        steps = [{"race": [st, st]}] + steps
    else:
        steps[i] = {"wait_" + r.choice(["blocks", "seconds"]): random_value(r)}
    return steps


def random_cases(seed, n):
    r = random.Random(seed)
    C = []
    for i in range(n):
        intents = r.random() < 0.15
        targets = V.INTENTS_TARGETS if intents else V.TARGETS
        steps = random_valid_steps(r, targets)
        tag = "rand-ok"
        if r.random() < 0.6:
            for _ in range(r.randint(1, 3)):
                steps = mutate(r, steps)
            tag = "rand-mut"
        C.append((f"{tag}-{i:05d}", doc_text(attack(steps)), "intents" if intents else "main"))
    # Chain Signatures suite: its own generator (seed + 1), so adding it left the main and
    # intents files above exactly as they were.
    r = random.Random(seed + 1)
    for i in range(n // 10):
        steps = random_valid_steps(r, V.CHAINSIG_TARGETS)
        tag = "rand-cs-ok"
        if r.random() < 0.6:
            for _ in range(r.randint(1, 3)):
                steps = mutate(r, steps)
            tag = "rand-cs-mut"
        C.append((f"{tag}-{i:05d}", doc_text(attack(steps)), "chainsig"))
    return C


