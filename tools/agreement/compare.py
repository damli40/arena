#!/usr/bin/env python3
"""Comparison test: does the gatekeeper agree with the engine on what an attack file means?

  python3 -I tools/agreement/compare.py [--seed N] [--random N] [--harness BIN] [--keep DIR]

Arena's step rules live in three copies: schema/attack.schema.json (for people),
tools/hunter/validate.py (the gatekeeper that admits files) and harness/src/seq.rs (the engine
that runs them). validate.py --self-test checks the first two agree. This checks the last two.

It writes a few thousand attack files (hand-picked cases at every limit, plus seeded random
mutations of valid files) and gives each to BOTH:
  - the gatekeeper: validate.validate_path(), exactly as the hunter and tools/check call it;
  - the engine's check-only path: `arena-harness check-seq` (harness/src/seqcheck.rs), which
    runs the real seq::load_sequence and then walks the steps the way seq::execute does,
    without starting a sandbox.

It FAILS (exit 1) when:
  - the gatekeeper accepts a file the engine refuses (a whole `run` stops at that file);
  - the gatekeeper accepts a file the engine would run differently: another step kind, another
    wait, another actor, target or method, other args (a number read as another type), other
    gas or deposit;
  - the gatekeeper crashes instead of giving a reason.
Files the engine accepts and the gatekeeper refuses are fine (the gatekeeper is meant to be
stricter); they are counted, not failed.

This is testing, not proof: it covers the cases it generates and the checks the engine makes
before it sends anything. What the six actions do on chain is not tested here.
Standard library only. Deterministic for a given --seed.
"""
